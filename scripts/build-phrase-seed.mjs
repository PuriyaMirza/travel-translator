// Writes db/seed/phrases.sql from data/phrases/*.csv.
// Usage: node scripts/build-phrase-seed.mjs
// The SQL is an idempotent upsert: re-running it updates rows in place.
import { mkdirSync, writeFileSync } from "node:fs";
import { readPhraseCsvs } from "./phraseCsv.mjs";

// Semicolons inside values are emitted as chr(59) so tools that split SQL on
// ";" (the Neon MCP runner does) can't cut a statement in half.
const q = (s) =>
  String(s)
    .split(";")
    .map((part) => `'${part.replace(/'/g, "''")}'`)
    .join(" || chr(59) || ");

const phrases = readPhraseCsvs();
const byLocale = Map.groupBy(phrases, (p) => p.locale);

const statements = [...byLocale].map(([locale, rows]) => {
  const values = rows
    .map(
      (p) =>
        `  (${[p.id, p.locale, p.category, p.sourceText, p.literal, p.natural, p.culturalNote, p.pronunciation]
          .map(q)
          .join(", ")}, ${p.sortOrder})`,
    )
    .join(",\n");
  return `-- ${locale}: ${rows.length} phrases
insert into phrases (id, locale, category, source_text, literal, natural_text, cultural_note, pronunciation, sort_order)
values
${values}
on conflict (id, locale) do update set
  category = excluded.category,
  source_text = excluded.source_text,
  literal = excluded.literal,
  natural_text = excluded.natural_text,
  cultural_note = excluded.cultural_note,
  pronunciation = excluded.pronunciation,
  sort_order = excluded.sort_order;`;
});

mkdirSync("db/seed", { recursive: true });
writeFileSync(
  "db/seed/phrases.sql",
  `-- Generated by scripts/build-phrase-seed.mjs from data/phrases/*.csv. Do not edit.\n\n${statements.join("\n\n")}\n`,
);
console.log(`db/seed/phrases.sql: ${phrases.length} phrases across ${byLocale.size} locales`);
