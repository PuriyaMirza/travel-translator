// Writes docs/review/spanish-review.md: every piece of authored Spanish still
// marked `review: draft`, laid out for a fluent speaker to read (SPEC.md §14).
//
//   node scripts/build-review-doc.mjs
//
// Regenerate it whenever the CSVs change. A row leaves this document when its
// `review` cell in the CSV is cleared.
import { mkdirSync, writeFileSync } from "node:fs";
import { readPhraseCsvs } from "./phraseCsv.mjs";

const LOCALE = "es-419";
const cell = (text) => String(text ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");

// Mirrors isHighStakes() in src/lib/review.ts.
const highStakes = (p) => p.category === "emergency" || (p.category === "dining" && p.moment === "dietary");

const drafts = readPhraseCsvs().filter((p) => p.locale === LOCALE && p.review === "draft");
const byCategory = Map.groupBy(drafts, (p) => p.category);

let doc = `# Spanish review

Everything below was written for the app and has **not yet been read by a fluent speaker**. It is live in the app now. Phrases marked **High-stakes** show a "still a draft" marker to users until they are reviewed.

Generated by \`scripts/build-review-doc.mjs\` from \`data/phrases/*.csv\`. Do not edit this file by hand; it is rebuilt from the CSVs.

## How to review

- The app uses neutral Latin American Spanish: no *vosotros*, formal *usted* with strangers, minimal regional slang.
- **Spanish** is what the traveller says. **More formal** is the safe textbook version, shown when it differs.
- **Pronunciation** is for an English speaker reading aloud: stressed syllable in CAPS, *c/z* as "s", *ll/y* as "y", *j* as "h".
- Write corrections in the **Reviewer notes** column, or leave it empty if the row is fine.
- Send the notes back and each checked row is marked reviewed, which removes its marker in the app.

## Phrases: pronunciation guides (${drafts.length})

The Spanish for these was already in the phrase list but hidden in the app because it had no pronunciation guide. The guides are new. Please check the Spanish as well as the guide.
`;

for (const [category, rows] of byCategory) {
  doc += `\n### ${category} (${rows.length})\n\n| | English | Spanish | More formal | Pronunciation | Reviewer notes |\n|---|---|---|---|---|---|\n`;
  for (const p of rows) {
    doc += `| ${highStakes(p) ? "**High-stakes**" : ""} | ${cell(p.sourceText)} | ${cell(p.natural)} | ${p.literal === p.natural ? "" : cell(p.literal)} | ${cell(p.pronunciation)} | |\n`;
  }
}

mkdirSync("docs/review", { recursive: true });
writeFileSync("docs/review/spanish-review.md", doc);
console.log(`docs/review/spanish-review.md: ${drafts.length} draft phrases`);
