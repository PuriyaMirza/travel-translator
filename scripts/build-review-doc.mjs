// Writes docs/review/spanish-review.md: every piece of authored Spanish still
// marked `review: draft`, laid out for a fluent speaker to read (SPEC.md §14).
//
//   node scripts/build-review-doc.mjs
//
// Regenerate it whenever the CSVs change. A row leaves this document when its
// `review` cell in the CSV is cleared.
import { mkdirSync, writeFileSync } from "node:fs";
import { readPhraseCsvs, readReplyCsvs, readSlotCsvs } from "./phraseCsv.mjs";

const LOCALE = "es-419";
const cell = (text) => String(text ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");

// Mirrors isHighStakes() in src/lib/review.ts.
const highStakes = (p) => p.category === "emergency" || (p.category === "dining" && p.moment === "dietary");

const allPhrases = readPhraseCsvs();
const drafts = allPhrases.filter(
  (p) => p.locale === LOCALE && p.review === "draft" && !p.sourceText.includes("{slot}"),
);
const byCategory = Map.groupBy(drafts, (p) => p.category);

let doc = `# Spanish review

Everything below was written for the app and has **not yet been read by a fluent speaker**. It is live in the app now. Phrases marked **High-stakes** show a "still a draft" marker to users until they are reviewed.

Generated by \`scripts/build-review-doc.mjs\` from \`data/phrases/*.csv\`. Do not edit this file by hand; it is rebuilt from the CSVs.

## How to review

- The app uses neutral Latin American Spanish: no *vosotros*, formal *usted* with strangers, minimal regional slang.
- **Spanish** is what the traveller says. **More formal** is the safe textbook version, shown when it differs.
- **Pronunciation** is for an English speaker reading aloud: stressed syllable in CAPS, *c/z* as "s", *ll/y* as "y", *j* as "h".
- Write corrections in the **Reviewer notes** column, or leave it empty if the row is fine.
- Send the notes back and each checked row is marked reviewed, which removes its marker in the app.

## Phrases: pronunciation guides (${drafts.length})

The Spanish for these was already in the phrase list but hidden in the app because it had no pronunciation guide. The guides are new. Please check the Spanish as well as the guide.
`;

for (const [category, rows] of byCategory) {
  doc += `\n### ${category} (${rows.length})\n\n| | English | Spanish | More formal | Pronunciation | Reviewer notes |\n|---|---|---|---|---|---|\n`;
  for (const p of rows) {
    doc += `| ${highStakes(p) ? "**High-stakes**" : ""} | ${cell(p.sourceText)} | ${cell(p.natural)} | ${p.literal === p.natural ? "" : cell(p.literal)} | ${cell(p.pronunciation)} | |\n`;
  }
}

// Likely replies (SPEC.md §14): what the other person may say back.
const phraseById = new Map(allPhrases.filter((p) => p.locale === LOCALE).map((p) => [p.id, p]));
const draftReplies = readReplyCsvs(allPhrases).filter((r) => r.locale === LOCALE && r.review === "draft");
if (draftReplies.length > 0) {
  doc += `
## Likely replies (${draftReplies.length})

What a local is likely to say back after the traveller says the phrase. The traveller only needs to recognise these, so there is no pronunciation guide. Please check that each reply is something a person would really say in that situation, and that the English meaning matches.
`;
  const byPhraseCategory = Map.groupBy(draftReplies, (r) => phraseById.get(r.phraseId).category);
  for (const [category, rows] of byPhraseCategory) {
    doc += `\n### ${category} (${rows.length})\n\n| | Traveller says | They might reply | Meaning | Reviewer notes |\n|---|---|---|---|---|\n`;
    for (const r of rows) {
      const p = phraseById.get(r.phraseId);
      doc += `| ${highStakes(p) ? "**High-stakes**" : ""} | ${cell(p.natural)} *(${cell(p.sourceText)})* | ${cell(r.text)} | ${cell(r.meaning)} | |\n`;
    }
  }
}

// Fill-in-the-blank options (SPEC.md §14).
const draftOptions = readSlotCsvs(allPhrases).filter((o) => o.locale === LOCALE && o.review === "draft");
if (draftOptions.length > 0) {
  doc += `
## Fill-in-the-blank phrases (${draftOptions.length} options)

Each of these is one sentence with a blank, and a list of things that can go in it. The app never joins Spanish words itself: every option is written out whole, article and preposition included, so that it reads correctly in its sentence (*al maní*, *a los mariscos*). Please read each option **inside its sentence** and check the agreement.
`;
  for (const [phraseId, rows] of Map.groupBy(draftOptions, (o) => o.phraseId)) {
    const p = phraseById.get(phraseId);
    doc += `\n### ${cell(p.sourceText.replace("{slot}", "___"))}${highStakes(p) ? " — **High-stakes**" : ""}\n\nSpanish: **${cell(p.natural.replace("{slot}", "___"))}**${p.literal === p.natural ? "" : ` · More formal: ${cell(p.literal.replace("{slot}", "___"))}`} · Pronunciation: ${cell(p.pronunciation.replace("{slot}", "___"))}\n\n| English | Goes in the blank | Full sentence | Pronunciation of the blank | Reviewer notes |\n|---|---|---|---|---|\n`;
    for (const o of rows) {
      doc += `| ${cell(o.sourceText)} | ${cell(o.natural)}${o.literal === o.natural ? "" : ` *(formal: ${cell(o.literal)})*`} | ${cell(p.natural.replace("{slot}", o.natural))} | ${cell(o.pronunciation)} | |\n`;
    }
  }
}

mkdirSync("docs/review", { recursive: true });
writeFileSync("docs/review/spanish-review.md", doc);
console.log(`docs/review/spanish-review.md: ${drafts.length} draft phrases, ${draftReplies.length} draft replies, ${draftOptions.length} draft options`);
